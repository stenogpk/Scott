import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'room_models.dart';

class LocalRoomServer {
  HttpServer? _server;
  final Set<WebSocket> _clients = {};
  final Map<String, WebSocket> _clientByPlayer = {};
  final Map<WebSocket, String> _playerByClient = {};
  final Map<String, RoomPlayer> _players = {};
  String? _hostId;
  String? _roomCode;
  int _targetScore = 150;
  Map<String, dynamic>? _gameState;

  String? get roomCode => _roomCode;
  int get port => _server?.port ?? 0;
  List<RoomPlayer> get players => List.unmodifiable(_players.values);

  Future<String> start({
    required String hostName,
    int targetScore = 150,
    int preferredPort = 8765,
    void Function(RoomSnapshot)? onRoomChanged,
    void Function(String, Map<String, dynamic>)? onAction,
  }) async {
    if (_server != null) throw StateError('Room server is already running.');
    final cleanHostName = hostName.trim();
    if (cleanHostName.isEmpty || cleanHostName.length > 24) {
      throw ArgumentError('Player name must contain 1 to 24 characters.');
    }
    if (targetScore <= 0) throw ArgumentError.value(targetScore, 'targetScore');

    _hostId = _randomId();
    _roomCode = _newRoomCode();
    _targetScore = targetScore;
    _players[_hostId!] = RoomPlayer(id: _hostId!, name: cleanHostName, isHost: true);
    try {
      _server = await HttpServer.bind(InternetAddress.anyIPv4, preferredPort);
    } catch (_) {
      _players.clear();
      _hostId = null;
      _roomCode = null;
      rethrow;
    }

    _server!.listen((request) async {
      if (!WebSocketTransformer.isUpgradeRequest(request)) {
        request.response
          ..statusCode = HttpStatus.ok
          ..write('SCOTT local room')
          ..close();
        return;
      }
      if (request.uri.queryParameters['code'] != _roomCode) {
        request.response
          ..statusCode = HttpStatus.forbidden
          ..write('Invalid room code')
          ..close();
        return;
      }

      final socket = await WebSocketTransformer.upgrade(request);
      _clients.add(socket);
      socket.listen((raw) {
        try {
          if (raw is! String || raw.length > 8192) {
            _sendError(socket, 'गलत संदेश मिला।');
            return;
          }
          final decoded = jsonDecode(raw);
          if (decoded is! Map) {
            _sendError(socket, 'गलत संदेश मिला।');
            return;
          }
          final msg = Map<String, dynamic>.from(decoded);

          if (msg['type'] == 'join') {
            if (_playerByClient.containsKey(socket)) {
              _sendError(socket, 'यह फोन पहले से कमरे में जुड़ा है।');
              return;
            }
            if (_gameState != null) {
              _sendError(socket, 'गेम शुरू हो चुका है; अब नया खिलाड़ी नहीं जुड़ सकता।');
              socket.close();
              return;
            }
            final name = (msg['name'] as String? ?? '').trim();
            if (name.isEmpty || name.length > 24) {
              _sendError(socket, 'नाम 1 से 24 अक्षरों के बीच रखें।');
              socket.close();
              return;
            }
            if (_players.length >= 5) {
              _sendError(socket, 'कमरा भर चुका है।');
              socket.close();
              return;
            }

            // Player IDs are generated by the host. Never trust an ID supplied by a client.
            final id = _randomId();
            _players[id] = RoomPlayer(id: id, name: name);
            _clientByPlayer[id] = socket;
            _playerByClient[socket] = id;
            socket.add(jsonEncode({
              'type': 'welcome',
              'playerId': id,
              'room': _snapshot().toJson(),
            }));
            _broadcast({'type': 'room', 'room': _snapshot().toJson()});
            onRoomChanged?.call(_snapshot());
          } else if (msg['type'] == 'action') {
            final id = _playerByClient[socket];
            final action = msg['action'];
            if (id == null || action is! Map || _gameState == null) {
              _sendError(socket, 'कमरे से जुड़ने के बाद ही चाल चल सकते हैं।');
              return;
            }
            final cleanAction = Map<String, dynamic>.from(action);
            if (!const {'show', 'discard'}.contains(cleanAction['type'])) {
              _sendError(socket, 'अमान्य चाल।');
              return;
            }
            onAction?.call(id, cleanAction);
          } else if (msg['type'] == 'ready') {
            final id = _playerByClient[socket];
            if (id == null || _gameState != null) return;
            final old = _players[id]!;
            _players[id] = RoomPlayer(
              id: old.id,
              name: old.name,
              isHost: old.isHost,
              isConnected: true,
              isReady: msg['ready'] == true,
            );
            _broadcast({'type': 'room', 'room': _snapshot().toJson()});
            onRoomChanged?.call(_snapshot());
          } else {
            _sendError(socket, 'अज्ञात अनुरोध।');
          }
        } catch (_) {
          _sendError(socket, 'गलत संदेश मिला।');
        }
      }, onDone: () {
        _removeClient(socket, onRoomChanged);
      }, onError: (_) {
        _removeClient(socket, onRoomChanged);
      });
    });
    return _roomCode!;
  }

  void _removeClient(WebSocket socket, void Function(RoomSnapshot)? onRoomChanged) {
    _clients.remove(socket);
    final id = _playerByClient.remove(socket);
    if (id != null) {
      _clientByPlayer.remove(id);
      if (_gameState == null) {
        _players.remove(id);
      } else {
        final old = _players[id];
        if (old != null) {
          _players[id] = RoomPlayer(
            id: old.id,
            name: old.name,
            isHost: old.isHost,
            isConnected: false,
            isReady: old.isReady,
          );
        }
      }
    }
    if (_roomCode != null) {
      _broadcast({'type': 'room', 'room': _snapshot().toJson()});
      onRoomChanged?.call(_snapshot());
    }
  }

  void _sendError(WebSocket socket, String message) {
    if (socket.readyState == WebSocket.open) {
      socket.add(jsonEncode({'type': 'error', 'message': message}));
    }
  }

  void updateGameState(
    Map<String, dynamic> state, {
    Map<String, List<Map<String, dynamic>>> privateHands = const {},
  }) {
    _gameState = state;
    for (final entry in _clientByPlayer.entries) {
      final socket = entry.value;
      if (socket.readyState == WebSocket.open) {
        socket.add(jsonEncode({
          'type': 'game',
          'state': state,
          'privateHand': privateHands[entry.key] ?? const [],
        }));
      }
    }
    _broadcast({'type': 'gamePublic', 'state': state});
  }

  void sendToPlayer(String playerId, Map<String, dynamic> message) {
    final socket = _clientByPlayer[playerId];
    if (socket != null && socket.readyState == WebSocket.open) {
      socket.add(jsonEncode(message));
    }
  }

  void setTargetScore(int value) {
    if (value <= 0) throw ArgumentError.value(value);
    if (_gameState != null) throw StateError('Game has already started.');
    _targetScore = value;
    _broadcast({'type': 'room', 'room': _snapshot().toJson()});
  }

  RoomSnapshot _snapshot() => RoomSnapshot(
    code: _roomCode!,
    hostId: _hostId!,
    players: players,
    targetScore: _targetScore,
    started: _gameState != null,
    gameState: _gameState,
  );

  void _broadcast(Map<String, dynamic> message) {
    final data = jsonEncode(message);
    for (final socket in _clients.toList()) {
      if (socket.readyState == WebSocket.open) socket.add(data);
    }
  }

  Future<void> close() async {
    for (final socket in _clients.toList()) {
      await socket.close();
    }
    _clients.clear();
    _clientByPlayer.clear();
    _playerByClient.clear();
    await _server?.close(force: true);
    _server = null;
    _players.clear();
    _roomCode = null;
    _hostId = null;
    _gameState = null;
  }

  String _newRoomCode() {
    const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    final random = Random.secure();
    return List.generate(6, (_) => chars[random.nextInt(chars.length)]).join();
  }

  String _randomId() =>
      '${DateTime.now().microsecondsSinceEpoch}-${Random.secure().nextInt(1 << 32)}';
}
